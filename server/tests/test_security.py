import base64
import os
import sys
import tempfile
import unittest
from unittest.mock import patch

from fastapi.testclient import TestClient

SERVER_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if SERVER_DIR not in sys.path:
    sys.path.insert(0, SERVER_DIR)

import security
import server

PINNED_EXT_ID = "a" * 32
OTHER_EXT_ID = "b" * 32
VALID_ORIGIN = f"chrome-extension://{PINNED_EXT_ID}"
OTHER_EXT_ORIGIN = f"chrome-extension://{OTHER_EXT_ID}"


def _mock_protect(plaintext: str) -> str:
    if not plaintext:
        return ""
    return "dpapi:" + base64.b64encode(plaintext.encode("utf-8")).decode("ascii")


def _mock_unprotect(stored):
    if not stored:
        return ""
    if stored.startswith("dpapi:"):
        return base64.b64decode(stored[len("dpapi:"):]).decode("utf-8")
    return stored


class TestBackendSecurityAndVault(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self._orig_db = server.DB_PATH
        self._orig_key = security.SECRET_KEY_PATH
        self._orig_pinned = security.PINNED_EXT_PATH
        self._orig_env_ext = os.environ.pop("LQS_EXTENSION_ID", None)

        server.DB_PATH = os.path.join(self._tmp.name, "test_lqs.db")
        security.SECRET_KEY_PATH = os.path.join(self._tmp.name, "secret.key")
        security.PINNED_EXT_PATH = os.path.join(self._tmp.name, "pinned_extension.json")

        server.init_db()
        self.client = TestClient(server.app)

    def tearDown(self):
        server.DB_PATH = self._orig_db
        security.SECRET_KEY_PATH = self._orig_key
        security.PINNED_EXT_PATH = self._orig_pinned
        if self._orig_env_ext is not None:
            os.environ["LQS_EXTENSION_ID"] = self._orig_env_ext
        self._tmp.cleanup()

    def _pair_primary_extension(self) -> dict:
        r = self.client.post(
            "/api/auth/pair",
            headers={"Origin": VALID_ORIGIN, "X-LQS-Client": "lavka-quality-shield"},
        )
        self.assertEqual(r.status_code, 200, r.text)
        data = r.json()
        self.assertEqual(data["extensionId"], PINNED_EXT_ID)
        self.assertEqual(len(data["token"]), 64)
        return {
            "Origin": VALID_ORIGIN,
            "X-LQS-Client": "lavka-quality-shield",
            "X-LQS-Token": data["token"],
        }

    def test_secret_key_autogenerated_32_bytes(self):
        token1 = security.load_or_create_secret_token()
        token2 = security.load_or_create_secret_token()
        self.assertEqual(token1, token2)
        self.assertEqual(len(bytes.fromhex(token1)), 32)
        self.assertTrue(os.path.exists(security.SECRET_KEY_PATH))

    def test_health_endpoint_ok_and_reports_pairing_state(self):
        r1 = self.client.get("/api/health")
        self.assertEqual(r1.status_code, 200)
        self.assertEqual(r1.json().get("status"), "ok")
        self.assertFalse(r1.json().get("paired"))

        self._pair_primary_extension()
        r2 = self.client.get("/api/health")
        self.assertEqual(r2.status_code, 200)
        self.assertTrue(r2.json().get("paired"))

    def test_unpaired_backend_rejects_protected_routes(self):
        token = security.load_or_create_secret_token()
        r = self.client.get(
            "/api/accounts/list",
            headers={
                "Origin": VALID_ORIGIN,
                "X-LQS-Client": "lavka-quality-shield",
                "X-LQS-Token": token,
            },
        )
        self.assertEqual(r.status_code, 403)

    def test_pairing_pins_first_extension_and_blocks_second(self):
        headers = self._pair_primary_extension()
        # Another extension trying to pair must be rejected
        r_other = self.client.post(
            "/api/auth/pair",
            headers={"Origin": OTHER_EXT_ORIGIN, "X-LQS-Client": "lavka-quality-shield"},
        )
        self.assertEqual(r_other.status_code, 403)

        # Re-pairing same extension without token must be rejected
        r_no_tok = self.client.post(
            "/api/auth/pair",
            headers={"Origin": VALID_ORIGIN, "X-LQS-Client": "lavka-quality-shield"},
        )
        self.assertEqual(r_no_tok.status_code, 403)

        # Re-pairing same extension WITH valid token succeeds
        r_ok = self.client.post("/api/auth/pair", headers=headers)
        self.assertEqual(r_ok.status_code, 200)
        self.assertTrue(r_ok.json().get("alreadyPaired"))

    def test_rejects_missing_or_wrong_token_and_foreign_extension_origin(self):
        headers = self._pair_primary_extension()

        # Missing token
        r1 = self.client.get(
            "/api/accounts/list",
            headers={"Origin": VALID_ORIGIN, "X-LQS-Client": "lavka-quality-shield"},
        )
        self.assertEqual(r1.status_code, 403)

        # Wrong token
        r2 = self.client.get(
            "/api/accounts/list",
            headers={
                "Origin": VALID_ORIGIN,
                "X-LQS-Client": "lavka-quality-shield",
                "X-LQS-Token": "0" * 64,
            },
        )
        self.assertEqual(r2.status_code, 403)

        # Another Chrome extension ID (even with the valid token!) must be blocked
        r3 = self.client.get(
            "/api/accounts/list",
            headers={
                "Origin": OTHER_EXT_ORIGIN,
                "X-LQS-Client": "lavka-quality-shield",
                "X-LQS-Token": headers["X-LQS-Token"],
            },
        )
        self.assertEqual(r3.status_code, 403)

        # External and Yandex origins blocked
        for bad_origin in [
            "https://evil.example.com",
            "https://lavka.yandex.ru",
            "http://127.0.0.1:9999",
            "http://localhost:3000",
        ]:
            r_bad = self.client.get(
                "/api/accounts/list",
                headers={
                    "Origin": bad_origin,
                    "X-LQS-Client": "lavka-quality-shield",
                    "X-LQS-Token": headers["X-LQS-Token"],
                },
            )
            self.assertEqual(r_bad.status_code, 403, f"Origin should be rejected: {bad_origin}")

        # Wrong X-LQS-Client header blocked
        r4 = self.client.get(
            "/api/accounts/list",
            headers={
                "Origin": VALID_ORIGIN,
                "X-LQS-Client": "wrong-client",
                "X-LQS-Token": headers["X-LQS-Token"],
            },
        )
        self.assertEqual(r4.status_code, 403)

    def test_all_sensitive_and_mutating_endpoints_require_auth(self):
        self._pair_primary_extension()
        endpoints = [
            ("GET", "/api/logs", None),
            ("GET", "/api/accounts/list", None),
            ("GET", "/api/accounts/acc_test_1/secrets", None),
            ("GET", "/api/price/list", None),
            ("GET", "/api/price/history/test_item", None),
            ("GET", "/api/watchlist", None),
            ("POST", "/api/watchlist/toggle", {"slug": "test_item", "title": "Test"}),
            ("DELETE", "/api/watchlist/test_item", None),
            ("GET", "/api/cart/latest", None),
            ("POST", "/api/save-cache", {"slug": "test", "title": "Test", "verdict": "ok"}),
            ("POST", "/api/analyze-product", {"title": "Test"}),
        ]
        for method, path, body in endpoints:
            r = self.client.request(method, path, json=body)
            self.assertEqual(r.status_code, 403, f"{method} {path} should require auth")

    def test_dynamic_cors_preflight_blocks_other_extensions_after_pin(self):
        self._pair_primary_extension()
        r_ok = self.client.options("/api/accounts/list", headers={"Origin": VALID_ORIGIN})
        self.assertEqual(r_ok.status_code, 204)
        self.assertEqual(r_ok.headers.get("access-control-allow-origin"), VALID_ORIGIN)
        self.assertIn("X-LQS-Token", r_ok.headers.get("access-control-allow-headers", ""))

        r_bad = self.client.options("/api/accounts/list", headers={"Origin": OTHER_EXT_ORIGIN})
        self.assertEqual(r_bad.status_code, 403)

    def test_protect_field_fail_closed_outside_windows(self):
        with patch.object(security.os, "name", "posix"):
            with self.assertRaises(RuntimeError):
                security._protect_field("super-secret-password")
            # Empty string is a no-op
            self.assertEqual(security._protect_field(""), "")
            # Reading unprotected record outside Windows also fails closed
            with self.assertRaises(RuntimeError):
                security._unprotect_field("plain-legacy-secret")

    def test_analyze_product_blocks_ssrf_ai_base_url(self):
        headers = self._pair_primary_extension()
        for bad_url in [
            "http://169.254.169.254/latest/meta-data",
            "http://192.168.1.1/v1",
            "file:///etc/passwd",
            "https://169.254.169.254/v1",
            "https://192.168.1.1/v1",
            "https://127.0.0.1:8765/v1",
            "https://localhost/v1",
        ]:
            r = self.client.post(
                "/api/analyze-product",
                json={"title": "Молоко 1л", "aiBaseUrl": bad_url},
                headers=headers,
            )
            self.assertEqual(r.status_code, 400, f"SSRF URL should be rejected: {bad_url}")

    @patch.object(security, "_unprotect_field", side_effect=_mock_unprotect)
    @patch.object(security, "_protect_field", side_effect=_mock_protect)
    def test_vault_save_partial_update_and_delete_roundtrip(self, _mock_enc, _mock_dec):
        headers = self._pair_primary_extension()
        payload = {
            "accountId": "acc_test_1",
            "label": "Test Account",
            "login": "tester",
            "password": "sample-value",
            "note": "unit test",
            "yandexLogin": "tester@yandex.ru",
            "cookieCount": 1,
            "cookies": [{"name": "Session_id", "value": "123"}],
            "localStorageData": {"theme": "dark"},
        }
        r_save = self.client.post("/api/accounts/save", json=payload, headers=headers)
        self.assertEqual(r_save.status_code, 200)

        # Partial metadata update (password & cookies omitted -> must preserve existing secrets)
        r_patch = self.client.post(
            "/api/accounts/save",
            json={
                "accountId": "acc_test_1",
                "label": "Test Account Renamed",
                "login": "tester",
                "note": "updated note",
            },
            headers=headers,
        )
        self.assertEqual(r_patch.status_code, 200)

        r_list = self.client.get("/api/accounts/list", headers=headers)
        self.assertEqual(r_list.status_code, 200)
        accounts = r_list.json().get("accounts", [])
        self.assertEqual(len(accounts), 1)
        self.assertEqual(accounts[0]["accountId"], "acc_test_1")
        self.assertEqual(accounts[0]["label"], "Test Account Renamed")
        self.assertEqual(accounts[0]["cookieCount"], 1)
        self.assertTrue(accounts[0]["hasPassword"])
        self.assertNotIn("password", accounts[0])
        self.assertNotIn("cookies", accounts[0])
        self.assertNotIn("localStorageData", accounts[0])

        # Secrets must be fetched on demand from the dedicated endpoint
        r_secrets = self.client.get("/api/accounts/acc_test_1/secrets", headers=headers)
        self.assertEqual(r_secrets.status_code, 200)
        sec_data = r_secrets.json()
        self.assertEqual(sec_data["password"], "sample-value")
        self.assertEqual(sec_data["cookies"][0]["name"], "Session_id")
        self.assertEqual(sec_data["localStorageData"], {"theme": "dark"})

        r_missing = self.client.get("/api/accounts/nonexistent/secrets", headers=headers)
        self.assertEqual(r_missing.status_code, 404)

        r_del = self.client.delete("/api/accounts/acc_test_1", headers=headers)
        self.assertEqual(r_del.status_code, 200)

        r_list_after = self.client.get("/api/accounts/list", headers=headers)
        self.assertEqual(r_list_after.json().get("accounts", []), [])

    def test_vault_dpapi_runtime_error_returns_503(self):
        headers = self._pair_primary_extension()
        with patch.object(security, "_protect_field", side_effect=RuntimeError("DPAPI unavailable")):
            r_save = self.client.post(
                "/api/accounts/save",
                json={"accountId": "acc_503", "label": "Fail Test", "password": "secret"},
                headers=headers,
            )
            self.assertEqual(r_save.status_code, 503)
            self.assertIn("DPAPI unavailable", r_save.json().get("detail", ""))

        with patch.object(security, "_protect_field", side_effect=_mock_protect):
            r_ok = self.client.post(
                "/api/accounts/save",
                json={"accountId": "acc_503", "label": "Fail Test", "password": "secret"},
                headers=headers,
            )
            self.assertEqual(r_ok.status_code, 200)

        with patch.object(security, "_unprotect_field", side_effect=RuntimeError("DPAPI decrypt failed")):
            r_sec = self.client.get("/api/accounts/acc_503/secrets", headers=headers)
            self.assertEqual(r_sec.status_code, 503)
            self.assertIn("DPAPI decrypt failed", r_sec.json().get("detail", ""))

    def test_validate_ai_base_url_rejects_unresolvable_host(self):
        headers = self._pair_primary_extension()
        with patch.object(security.socket, "getaddrinfo", side_effect=OSError("Name or service not known")):
            r = self.client.post(
                "/api/analyze-product",
                json={"title": "Молоко 1л", "aiBaseUrl": "https://nonexistent.invalid/v1"},
                headers=headers,
            )
            self.assertEqual(r.status_code, 400)
            self.assertEqual(r.json().get("detail"), "Invalid aiBaseUrl: host could not be resolved.")


